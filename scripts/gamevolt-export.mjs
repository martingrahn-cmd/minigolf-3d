// Writes what GameVolt needs to know about Mini Mayhem's trophies, from the
// list the game itself uses (src/trophies.js), so the two cannot drift apart.
// GameVolt is in English, so the names come from the English dictionary.
//   gamevolt/achievement_defs.sql — the game row and its 31 trophies, for the Supabase SQL editor
//   gamevolt/trophy_catalog.js    — the entry for TROPHY_CATALOG in GameVolt's /profile/index.html
// Run from the repo root:  node scripts/gamevolt-export.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { TROPHIES, GAME_ID } from '../src/trophies.js';
import en from '../src/locales/en.js';

const english=s=>en[s]??s;
const sql=v=>`'${String(v).replace(/'/g,"''")}'`;
const js=v=>`'${String(v).replace(/\\/g,'\\\\').replace(/'/g,"\\'")}'`;
const dir=new URL('../gamevolt/',import.meta.url);
mkdirSync(dir,{recursive:true});

const rows=TROPHIES.map((t,i)=>`  (${[`${GAME_ID}-${t.id}`,GAME_ID,english(t.name),english(t.desc),t.icon,t.tier].map(sql).join(', ')}, ${i+1})`);
writeFileSync(new URL('achievement_defs.sql',dir),`-- Mini Mayhem — GameVolt game registration and 31 trophy definitions
-- (15 bronze, 10 silver, 5 gold, 1 platinum). Idempotent: safe to run again
-- in the Supabase SQL editor.
-- Generated by scripts/gamevolt-export.mjs from src/trophies.js; do not edit by hand.

BEGIN;

INSERT INTO games (id, title, description, thumbnail_url) VALUES
  (${sql(GAME_ID)}, 'Mini Mayhem', '3D mini golf across four worlds: Clockwork City, Cloud Forest, Moon Carnival and Haunted Harbour.', '/assets/thumbnails/${GAME_ID}.webp')
ON CONFLICT (id) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  thumbnail_url = EXCLUDED.thumbnail_url;

DELETE FROM achievement_defs WHERE game_id = ${sql(GAME_ID)};

INSERT INTO achievement_defs (id, game_id, title, description, icon, tier, sort_order) VALUES
${rows.join(',\n')};

COMMIT;
`);

writeFileSync(new URL('trophy_catalog.js',dir),`// Mini Mayhem's entry for TROPHY_CATALOG in GameVolt's /profile/index.html.
// Generated by scripts/gamevolt-export.mjs from src/trophies.js; do not edit by hand.
'${GAME_ID}': [
${TROPHIES.map(t=>`    { id:${js(`${GAME_ID}-${t.id}`)}, icon:${js(t.icon)}, name:${js(english(t.name))}, desc:${js(english(t.desc))}, tier:${js(t.tier)} },`).join('\n')}
],
`);
console.log(`wrote ${TROPHIES.length} trophies to gamevolt/`);
